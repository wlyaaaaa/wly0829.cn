import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const registry = JSON.parse(await readFile(path.join(projectRoot, "config", "panel-projects.json"), "utf8"));
const outputPath = path.join(projectRoot, "app", "project-content-index.generated.js");
const enabled = registry.projects.filter((item) => item.enabled).sort((left, right) => left.order - right.order);

function safeIdentifier(id) {
  return id.replace(/[^A-Za-z0-9_]/g, "_");
}

function safeImportPath(contentPath) {
  const absolute = path.resolve(projectRoot, contentPath);
  const relative = path.relative(path.join(projectRoot, "app"), absolute).replaceAll("\\", "/");
  if (!relative || relative.startsWith("../") || path.isAbsolute(relative) || !relative.endsWith(".js")) {
    throw new Error(`Project content path must stay inside app and end in .js: ${contentPath}`);
  }
  return relative.startsWith(".") ? relative : `./${relative}`;
}

const imports = [];
const rows = [];
for (const registration of enabled) {
  if (!registration.ai_refresh?.content_path) throw new Error(`Enabled project lacks ai_refresh.content_path: ${registration.id}`);
  const identifier = safeIdentifier(registration.id);
  imports.push(`import { project as project_${identifier}, modules as modules_${identifier} } from ${JSON.stringify(safeImportPath(registration.ai_refresh.content_path))};`);
  rows.push(`  [${JSON.stringify(registration.id)}, { project: project_${identifier}, modules: modules_${identifier}, kind: ${JSON.stringify(registration.id)} }]`);
}

const source = `// Generated by scripts/generate-project-content-index.mjs. Do not hand-edit.\n${imports.join("\n")}\n\nexport const projectContentPackages = new Map([\n${rows.join(",\n")}\n]);\n`;
let current = "";
try { current = await readFile(outputPath, "utf8"); } catch {}
if (current !== source) await writeFile(outputPath, source, "utf8");

process.stdout.write(`${JSON.stringify({ schema: "wly.project-content-index-generation.v1", status: current === source ? "no_change" : "generated", project_count: enabled.length, output: outputPath }, null, 2)}\n`);
